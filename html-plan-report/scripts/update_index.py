#!/usr/bin/env python3
"""Rebuild the plan index. Standard library only.

Usage:
  python3 scripts/update_index.py [PLAN_DIR] [--title "Forge plans"] [--migrate]     (default folder: .plan)

1. Syncs PLAN_DIR/_assets/ (plan.css, plan.js) from the skill, only when the skill's copy is newer.
2. With --migrate, converts plans that still inline the template's CSS and script to link _assets/.
3. Writes PLAN_DIR/index.html: one card per plan, newest first, plans waiting for an answer on top.
--title names the index once; later runs reuse it. Run this whenever a plan is created, revised or
changes status. Hand edits to index.html and _assets/ are overwritten.
"""
import datetime as dt
import html
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate_plan import parse  # noqa: E402  (same folder, same parser)

BADGE = {
    "draft": ("info", "Draft"), "awaiting": ("warn", "Awaiting approval"), "approved": ("ok", "Approved"),
    "implemented": ("ok", "Implemented"), "implemented-deviations": ("warn", "Implemented with deviations"),
    "superseded": ("info", "Superseded"),
}
PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="generator" content="html-plan-report/scripts/update_index.py">
<meta name="plan-index-title" content="%(title_attr)s">
<title>%(title)s</title>
<link rel="stylesheet" href="_assets/plan.css">
<script src="_assets/plan.js"></script>
</head>
<body>
<!-- Generated by update_index.py. Hand edits are overwritten. -->
<div class="page">
<main id="main">
<header>
  <h1>%(title)s</h1>
  <p class="lede">Implementation plans for %(name)s, newest first. Each one is a self-contained page written with the <code>html-plan-report</code> skill: open it, compare the decisions, and answer them in Claude Code.</p>
  <div class="meta"><span>%(counts)s</span><span>Updated %(today)s</span></div>
  <input class="filter" type="search" placeholder="Filter by title, status or text" aria-label="Filter plans" hidden>
</header>

%(body)s
</main>
</div>
</body>
</html>
"""


def first(root, pred):
    found = root.find_all(pred)
    return found[0] if found else None


def plural(n, word):
    return f"{n} {word}{'s' if n != 1 else ''}"


def read_plan(path):
    _, tb = parse(path)
    root = tb.root
    meta = first(root, lambda n: n.tag == "meta" and n.attrs.get("name") == "plan-template")
    if meta is None:
        return None
    h1 = first(root, lambda n: n.tag == "h1")
    lede = first(root, lambda n: "lede" in n.classes())
    badge = first(root, lambda n: "status" in n.classes() and "badge" in n.classes())
    ver = first(root, lambda n: "data-version" in n.attrs)
    when = first(root, lambda n: n.tag == "time" and n.attrs.get("datetime"))
    status = badge.attrs.get("data-status", "") if badge else ""
    iso = when.attrs["datetime"] if when else ""
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", iso):
        iso = dt.date.fromtimestamp(path.stat().st_mtime).isoformat()
    ds = root.find_all(lambda n: n.tag == "div" and "decision" in n.classes())
    return {
        "file": path.name, "title": h1.get_text() if h1 else path.stem, "lede": lede.get_text() if lede else "",
        "status": status, "version": ver.attrs["data-version"] if ver else "", "iso": iso,
        "kind": meta.attrs.get("content", "full"),
        "mtime": int(path.stat().st_mtime),
        "steps": len(root.find_all(lambda n: n.tag == "li" and n.attrs.get("data-step"))),
        "decisions": len(ds),
        "open": sum(1 for d in ds if "data-decided" not in d.attrs) if status == "awaiting" else 0,
    }


def card(p):
    e = html.escape
    cls, label = BADGE.get(p["status"], ("info", p["status"] or "No status"))
    bits = [f'<span class="badge {cls}">{e(label)}</span>']
    if p["open"]:
        bits.append(f'<span class="badge warn">{plural(p["open"], "decision")} open</span>')
    if p["version"]:
        bits.append(f'<span>Version {e(p["version"])}</span>')
    bits.append(f'<time datetime="{e(p["iso"])}">{e(p["iso"])}</time>')
    size = [plural(p["steps"], "step")] if p["steps"] else []
    if p["decisions"] and not p["open"]:
        size.append(plural(p["decisions"], "decision"))
    if size:
        bits.append(f'<span>{", ".join(size)}</span>')
    if p["kind"] == "lite":
        bits.append("<span>lite</span>")
    bits.append(f'<span>{e(p["file"])}</span>')
    cls_card = "plan-card superseded" if p["status"] == "superseded" else "plan-card"
    lede = f'\n      <p>{e(p["lede"])}</p>' if p["lede"] else ""
    return (f'    <li class="{cls_card}">\n'
            f'      <a class="plan-link" href="{e(p["file"], quote=True)}">{e(p["title"])}</a>{lede}\n'
            f'      <div class="meta">{"".join(bits)}</div>\n'
            f'    </li>')


def group(gid, heading, plans):
    cards = "\n".join(card(p) for p in plans)
    return (f'<section class="group" aria-labelledby="{gid}">\n  <h2 id="{gid}">{html.escape(heading)}</h2>\n'
            f'  <ul class="cards">\n{cards}\n  </ul>\n</section>')


def previous_title(plan_dir):
    idx = plan_dir / "index.html"
    if idx.exists():
        m = re.search(r'<meta name="plan-index-title" content="([^"]*)">', idx.read_text(encoding="utf-8"))
        if m:
            return html.unescape(m.group(1))
    return None


def build(plan_dir, title=None):
    plans = [p for p in (read_plan(f) for f in plan_dir.glob("*.plan.html")) if p]
    plans.sort(key=lambda p: (p["iso"], p["file"]), reverse=True)
    repo = plan_dir.resolve().parent.name
    title = title or previous_title(plan_dir) or f"{repo} plans"
    name = re.sub(r"\s+plans$", "", title, flags=re.I) or repo
    waiting = [p for p in plans if p["status"] == "awaiting"]
    rest = [p for p in plans if p["status"] != "awaiting"]
    sections = []
    if waiting:
        sections.append(group("waiting", "Waiting for you", waiting))
    if rest:
        sections.append(group("plans", "Plans", rest))
    counts = plural(len(plans), "plan") + (f", {len(waiting)} waiting for you" if waiting else "")
    page = PAGE % {
        "title": html.escape(title), "title_attr": html.escape(title, quote=True), "name": html.escape(name),
        "counts": counts, "today": dt.date.today().isoformat(),
        "body": "\n\n".join(sections) or "<section><p>No plans yet.</p></section>",
    }
    return page, len(plans)


ASSETS = ("plan.css", "plan.js")
SKILL_ASSETS = Path(__file__).resolve().parent.parent / "assets"
STAMP = re.compile(r"html-plan-report assets v(\d{4})\.(\d{2})\.(\d{2})-(\d+)")


def version(path):
    m = STAMP.search(path.read_text(encoding="utf-8")[:300]) if path.exists() else None
    return tuple(int(x) for x in m.groups()) if m else None


def sync_assets(plan_dir):
    """Copy plan.css and plan.js into PLAN_DIR/_assets/ when missing or older. Never downgrade."""
    dst_dir = plan_dir / "_assets"
    dst_dir.mkdir(exist_ok=True)
    notes = []
    for name in ASSETS:
        src, dst = SKILL_ASSETS / name, dst_dir / name
        have, new = version(dst), version(src)
        if have is None or (new and new > have):
            tmp = dst.with_suffix(dst.suffix + ".tmp")
            tmp.write_bytes(src.read_bytes())
            tmp.replace(dst)
            notes.append(f"{name}: {'added' if have is None else 'upgraded'} v{'.'.join(map(str, new))}")
        elif new and new < have:
            notes.append(f"{name}: kept v{'.'.join(map(str, have))}, newer than this skill's v{'.'.join(map(str, new))}")
    return notes


TEMPLATE_STYLE = re.compile(r"<style>(?=[^<]*--accent)(?=[^<]*--surface)[^<]*</style>\n?", re.S)
TEMPLATE_SCRIPT = re.compile(r"<script>\s*/\*\s*Optional enhancements.*?</script>\n?", re.S)
LINKS = '<link rel="stylesheet" href="_assets/plan.css">\n<script src="_assets/plan.js"></script>\n'


def migrate(plan_dir):
    """Replace a plan's inlined template CSS and script with links to _assets/. Other blocks are kept."""
    changed = []
    for f in sorted(plan_dir.glob("*.plan.html")):
        s = f.read_text(encoding="utf-8")
        if "_assets/plan.css" in s or not TEMPLATE_STYLE.search(s):
            continue
        s = TEMPLATE_STYLE.sub("", s, count=1)
        s = TEMPLATE_SCRIPT.sub("", s, count=1)
        s = s.replace("</head>", LINKS + "</head>", 1)
        f.write_text(s, encoding="utf-8")
        changed.append(f.name)
    return changed


def previous_title_from_page(page):
    m = re.search(r'<meta name="plan-index-title" content="([^"]*)">', page)
    return html.unescape(m.group(1)) if m else None


def write_manifest(plan_dir, title=None):
    """_assets/plans.js: the list of plans every page shows on the left. A script, since fetch() is blocked from disk."""
    import json
    plans = [p for p in (read_plan(f) for f in plan_dir.glob("*.plan.html")) if p]
    waiting = sorted((p for p in plans if p["status"] == "awaiting"), key=lambda p: (p["iso"], p["file"]), reverse=True)
    rest = sorted((p for p in plans if p["status"] != "awaiting"), key=lambda p: (p["iso"], p["file"]), reverse=True)
    repo = plan_dir.resolve().parent.name
    data = {"title": title or previous_title(plan_dir) or f"{repo} plans",
            "plans": [{k: p[k] for k in ("file", "title", "lede", "status", "open", "iso", "kind", "mtime")} for p in waiting + rest]}
    out = plan_dir / "_assets" / "plans.js"
    out.write_text("/* Generated by update_index.py: the plans list shown on every page. Hand edits are overwritten. */\n"
                   "window.PLAN_INDEX = " + json.dumps(data, ensure_ascii=False, indent=1).replace("</", "<\\/") + ";\n", encoding="utf-8")


def main(argv):
    title = None
    if "--title" in argv:
        i = argv.index("--title")
        if i + 1 >= len(argv):
            print('ERROR  --title needs a value, for example --title "Forge plans"', file=sys.stderr)
            return 2
        title = argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    do_migrate = "--migrate" in argv
    argv = [a for a in argv if a != "--migrate"]
    if len(argv) > 1 or (argv and argv[0].startswith("-")):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    plan_dir = Path(argv[0] if argv else ".plan")
    if not plan_dir.is_dir():
        print(f"ERROR  no such folder: {plan_dir}", file=sys.stderr)
        return 2
    for note in sync_assets(plan_dir):
        print(f"_assets/{note}")
    if do_migrate:
        done = migrate(plan_dir)
        print(f"migrated {len(done)} plan{'s' if len(done) != 1 else ''} to _assets/" + (": " + ", ".join(done) if done else ""))
    page, n = build(plan_dir, title)
    write_manifest(plan_dir, title or previous_title_from_page(page))
    tmp = plan_dir / "index.html.tmp"
    tmp.write_text(page, encoding="utf-8")
    tmp.replace(plan_dir / "index.html")
    print(f"{plan_dir / 'index.html'}: {plural(n, 'plan')}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
